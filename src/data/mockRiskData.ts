export const GENERATE_TIME_SERIES = (
  baseRainfall: number,
  baseMoisture: number,
  baseMovement: number,
  baseRisk: number,
  range: '24h' | '7d' | '30d'
): EnvironmentalTelemetry['series'] => {
  const points: EnvironmentalTelemetry['series'] = [];

  if (range === '24h') {
    const hours = ['00:00', '03:00', '06:00', '09:00', '12:00', '15:00', '18:00', '21:00'];
    hours.forEach((h, idx) => {
      const progression = (idx + 1) / hours.length;
      points.push({
        time: h,
        rainfall: Math.round((baseRainfall * (0.4 + 0.6 * progression)) / 4),
        soilMoisture: Math.min(99, Math.round(baseMoisture * (0.75 + 0.25 * progression))),
        groundMovement: parseFloat((baseMovement * (0.3 + 0.7 * progression)).toFixed(1)),
        riskScore: Math.min(100, Math.round(baseRisk * (0.65 + 0.35 * progression))),
      });
    });
  } else if (range === '7d') {
    const days = ['Day -6', 'Day -5', 'Day -4', 'Day -3', 'Day -2', 'Yesterday', 'Today'];
    days.forEach((d, idx) => {
      const progression = (idx + 1) / days.length;
      points.push({
        time: d,
        rainfall: Math.round(baseRainfall * (0.3 + 0.7 * progression * Math.sin(idx + 1))),
        soilMoisture: Math.min(98, Math.round(baseMoisture * (0.7 + 0.3 * progression))),
        groundMovement: parseFloat((baseMovement * (0.2 + 0.8 * progression)).toFixed(1)),
        riskScore: Math.min(100, Math.round(baseRisk * (0.5 + 0.5 * progression))),
      });
    });
  } else {
    const weeks = ['Week 1', 'Week 2', 'Week 3', 'Week 4'];
    weeks.forEach((w, idx) => {
      const progression = (idx + 1) / weeks.length;
      points.push({
        time: w,
        rainfall: Math.round(baseRainfall * 2.8 * (0.4 + 0.6 * progression)),
        soilMoisture: Math.min(95, Math.round(baseMoisture * (0.65 + 0.35 * progression))),
        groundMovement: parseFloat((baseMovement * 2.5 * (0.2 + 0.8 * progression)).toFixed(1)),
        riskScore: Math.min(100, Math.round(baseRisk * (0.4 + 0.6 * progression))),
      });
    });
  }

  return points;
};
